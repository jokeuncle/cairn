"""Tests for cairn.tools.get_section and cairn.tools.expand."""

from __future__ import annotations

from pathlib import Path

import pytest

from cairn.core.errors import IndexNotFoundError, ToolError
from cairn.index.tree import Tree, TreeBuilder
from cairn.ingest.markdown import MarkdownParser
from cairn.tools.base import DocumentIndex, estimate_tokens_of_payload
from cairn.tools.get_section import expand, get_section


class TestGetSection:
    async def test_default_level_is_synopsis(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction")
        assert resp.data["level"] == "synopsis"
        # FakeSummarizer produces non-empty synopsis from the body.
        assert resp.data["content"]

    async def test_level_gist(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="gist")
        assert resp.data["level"] == "gist"
        assert resp.data["content"]

    async def test_level_full_returns_raw_text(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="full")
        assert "This is the intro body" in resp.data["content"]

    async def test_digest_returned_since_v024(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="digest")
        assert resp.data["level"] == "digest"
        assert resp.data["content"]

    async def test_missing_section_id(self, index: DocumentIndex) -> None:
        with pytest.raises(IndexNotFoundError):
            await get_section(index, id="ghost")

    async def test_include_children_reserved(self, index: DocumentIndex) -> None:
        with pytest.raises(ToolError):
            await get_section(index, id="introduction", include_children=True)

    async def test_anchor_includes_doc_and_id(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction/quickstart")
        assert resp.data["anchor"] == "cairn://simple/introduction/quickstart"

    async def test_path_is_breadcrumb(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction/quickstart")
        assert resp.data["path"] == ["Introduction", "Quickstart"]

    async def test_has_children_flag(self, index: DocumentIndex) -> None:
        intro = await get_section(index, id="introduction")
        leaf = await get_section(index, id="introduction/quickstart")
        assert intro.data["has_children"] is True
        assert leaf.data["has_children"] is False

    async def test_next_levels_available_at_synopsis(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="synopsis")
        # Since v0.2.4 digest is generated by default; next from synopsis is
        # digest then full.
        assert resp.data["next_levels_available"] == ["digest", "full"]

    async def test_next_levels_available_at_gist(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="gist")
        # synopsis exists, digest doesn't, full always does.
        assert "synopsis" in resp.data["next_levels_available"]
        assert "full" in resp.data["next_levels_available"]

    async def test_tokens_match_content(self, index: DocumentIndex) -> None:
        resp = await get_section(index, id="introduction", level="full")
        # Non-empty content → non-zero tokens.
        assert resp.tokens_returned > 0

    async def test_full_body_exposes_unread_child_and_root_sibling(
        self, index: DocumentIndex
    ) -> None:
        resp = await get_section(index, id="introduction", level="full")
        assert "Install with pip" not in resp.data["content"]
        assert "descendant" in resp.data["content_scope"]
        nav = resp.data["navigation"]
        child = nav["children"][0]
        assert child["anchor"] == "cairn://simple/introduction/quickstart"
        body = await get_section(index, id=child["id"], level="full")
        assert "Install with pip" in body.data["content"]
        assert [entry["id"] for entry in nav["siblings"]] == ["reference"]
        assert resp.tokens_returned == estimate_tokens_of_payload(resp.data)

    async def test_leaf_lists_siblings_without_claiming_children(
        self, index: DocumentIndex
    ) -> None:
        resp = await get_section(index, id="introduction/quickstart", level="full")
        nav = resp.data["navigation"]
        assert nav["children"] == []
        assert nav["children_total"] == 0
        assert [entry["id"] for entry in nav["siblings"]] == ["introduction/configuration"]
        assert nav["outline"] == {"doc": "simple", "depth": 6, "focus": "introduction"}

    async def test_navigation_is_bounded_and_reports_omissions(
        self, index: DocumentIndex, tmp_path: Path
    ) -> None:
        markdown = "# Root\n\nParent body.\n\n" + "\n".join(
            f"## Child {number}\n\nBody {number}.\n" for number in range(12)
        )
        markdown += "\n" + "\n".join(f"# Peer {number}\n\nPeer.\n" for number in range(12))
        doc = MarkdownParser().parse(markdown, doc_id=index.doc_id)
        TreeBuilder().build(doc, out_dir=tmp_path)
        index.tree = Tree.load(tmp_path)
        resp = await get_section(index, id="root", level="full")
        nav = resp.data["navigation"]
        assert nav["children_total"] == nav["siblings_total"] == 12
        assert len(nav["children"]) == len(nav["siblings"]) == 8
        assert "Body 0" not in resp.data["content"]


class TestExpand:
    async def test_equivalent_to_get_section(self, index: DocumentIndex) -> None:
        a = await get_section(index, id="introduction", level="full")
        b = await expand(index, id="introduction", to="full")
        assert a.data == b.data
